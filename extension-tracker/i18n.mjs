export const MESSAGE_KEYS = Object.keys(messages['zh-CN']);
export const PROGRESS_ERROR_CODES = MESSAGE_KEYS.filter(key => /^error\.[A-Z_]+$/u.test(key))
  .map(key => key.slice('error.'.length));

export function translate(locale, key, values = {}) {
  const template = messages[normalizeLocale(locale)][key] ?? messages['zh-CN'][key] ?? key;
  return template.replace(/\{([a-zA-Z]+)\}/gu, (placeholder, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}

export function formatDate(locale, value) {
  const date = new Date(value);
  return Number.isFinite(date.getTime()) ? date.toLocaleString(normalizeLocale(locale)) : String(value);
}
