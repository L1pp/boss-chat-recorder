export const SUPPORTED_LOCALES = ['zh-CN', 'en'];

// Adapt explicitly Chinese browser languages; use English for every other or unknown language.
export function normalizeLocale(value) {
  const language = typeof value === 'string' ? value.toLowerCase().split(/[-_]/u)[0] : '';
  return language === 'zh' ? 'zh-CN' : 'en';
}

export function resolveLocale(preference, browserLanguage) {
  return SUPPORTED_LOCALES.includes(preference) ? preference : normalizeLocale(browserLanguage);
}

